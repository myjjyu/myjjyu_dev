/**
 * 📌 공인중개서 1차 시험은 개론, 민법2개 과목이 있습니다
 * 과목마다 100점 만점이지만 두 과목 합해서 120점 이상이면 합격시켜줍니다
 * 다만 한 과목이 40점 미만이면 과락으로 불합격 됩니다 
 * 과목 점수 2개를 파라미터로 입력하면 합격인지 불합격인지 여부를 콘솔창에 출력하는 함수를 만들어보십시오.
 * 합격판독기에 0에서 100사이 숫자가 아닌걸 입력하면 장난치지 말라고 alert를 띄우기
 */

function testScore(score1, score2) {
  // 점수가 0에서 100 사이의 숫자가 아닌 경우
  if (score1 < 0 || score1 > 100 || score2 < 0 || score2 > 100) {
    console.log('장난치지말고 0에서 100사이 숫자를 입력해주세요 🤬');
  // 한 과목이 40점 미만인 경우
  } else if (score1 < 40 || score2 < 40) {
    console.log('불합격');
  // 두 과목 합해서 120점 이상인 경우
  } else if (score1 + score2 >= 120) {
    console.log('합격');
  // 그 외의 경우
  } else {
    console.log('불합격');
  }
}

// 함수 호출 예시
testScore(70, 70);  // 합격
testScore(30, 100); // 불합격
testScore(50, 50);  // 불합격
testScore(110, 50); // 장난치지말고 0에서 100사이 숫자를 입력해주세요 🤬